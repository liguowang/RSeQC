"""Normalize a BigWig signal to a fixed total WIG sum.

The normalization, chunking, WIG output, and bedGraph output algorithms are
preserved from the original implementation.
"""

from __future__ import annotations
import argparse
import collections
import sys
from itertools import groupby
from operator import itemgetter
from pathlib import Path
from typing import Iterable, Sequence
import numpy as np
import pyBigWig
from qcmodule import BED
from importlib.metadata import version

__version__ = version("RSeQC")
__author__ = "Liguo Wang"


DESCRIPTION = (
    "Normalize a BigWig signal to a user-specified total WIG sum and write "
    "the normalized values as WIG or bedGraph."
)

EPILOG = """
Examples
--------
Normalize the entire BigWig and write bedGraph:
    normalize_bigwig.py -i sample.bw -o sample.normalized.bedGraph -t 100000000 -f bgr

Calculate the normalization factor from annotated exons only:
    normalize_bigwig.py -i sample.bw -o sample.normalized.wig -r genes.bed12 -f wig

Notes
-----
* A target WIG sum of 100,000,000 corresponds to the coverage generated by
  one million 100-nt reads.
* When --refgene is supplied, only signal overlapping merged exons is used to
  calculate the normalization factor.
"""


def build_parser() -> argparse.ArgumentParser:
    """Create and configure the command-line parser."""
    parser = argparse.ArgumentParser(
        description=DESCRIPTION,
        epilog=EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "-i",
        "--bwfile",
        dest="bigwig_file",
        required=True,
        type=Path,
        help="Input BigWig file.",
    )
    parser.add_argument(
        "-o",
        "--output",
        dest="output_file",
        required=True,
        type=Path,
        help="Output WIG or bedGraph file.",
    )
    parser.add_argument(
        "-t",
        "--wigsum",
        dest="total_wigsum",
        type=float,
        default=100_000_000,
        metavar="FLOAT",
        help="Target total WIG sum. Default: %(default)s",
    )
    parser.add_argument(
        "-r",
        "--refgene",
        dest="refgene_bed",
        type=Path,
        help=(
            "Optional BED gene model. When supplied, the normalization factor "
            "is calculated from merged exon regions only."
        ),
    )
    parser.add_argument(
        "-c",
        "--chunk",
        dest="chunk_size",
        type=int,
        default=500_000,
        metavar="INT",
        help=(
            "Chromosome chunk size in bp. Smaller chunks use less memory. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "-f",
        "--format",
        dest="out_format",
        choices=("wig", "bgr"),
        type=str.lower,
        default="bgr",
        help=(
            "Output format: 'wig' for variableStep WIG or 'bgr' for "
            "bedGraph. Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow an existing output file to be replaced.",
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
    )

    return parser


def validate_args(parser: argparse.ArgumentParser, args: argparse.Namespace) -> None:
    """Validate command-line arguments."""
    if not args.bigwig_file.is_file():
        parser.error(f"input BigWig file does not exist: {args.bigwig_file}")

    if args.refgene_bed is not None and not args.refgene_bed.is_file():
        parser.error(f"reference BED file does not exist: {args.refgene_bed}")

    if args.total_wigsum <= 0:
        parser.error("--wigsum must be greater than zero")

    if args.chunk_size <= 0:
        parser.error("--chunk must be greater than zero")

    output_parent = args.output_file.parent
    if not output_parent.exists():
        parser.error(f"output directory does not exist: {output_parent}")

    if not output_parent.is_dir():
        parser.error(f"output parent is not a directory: {output_parent}")

    if args.output_file.exists() and not args.overwrite:
        parser.error(
            f"output file already exists: {args.output_file}; "
            "use --overwrite to replace it"
        )


def chromosome_chunks(
    chromosome: str,
    chromosome_size: int,
    chunk_size: int,
) -> Iterable[tuple[str, int, int]]:
    """Yield chromosome chunks using the original BED tiling helper."""
    yield from BED.tillingBed(
        chrName=chromosome,
        chrSize=chromosome_size,
        stepSize=chunk_size,
    )


def signal_sum(
    bigwig,
    chromosome: str,
    start: int,
    end: int,
) -> float:
    """Return the summed BigWig signal for one interval."""
    statistics = bigwig.stats(chromosome, start, end)
    if not statistics or statistics[0] is None:
        return 0.0

    values = bigwig.values(chromosome, start, end)
    total = float(np.nansum(values))

    if np.isnan(total):
        return 0.0

    return total


def calculate_exonic_wigsum(
    bigwig,
    refgene_bed: Path,
) -> float:
    """Calculate WIG sum over merged exons using the original algorithm."""
    print(f"Extract exons from {refgene_bed}", file=sys.stderr)

    bed = BED.ParseBED(str(refgene_bed))
    exons = bed.getExon()

    print("Merge overlapping exons ...", file=sys.stderr)
    merged_exons = BED.unionBed3(exons)

    print(
        f"Calculate WIG sum covered by {refgene_bed} only",
        file=sys.stderr,
    )

    wig_sum = 0.0

    for chromosome, start, end in merged_exons:
        try:
            wig_sum += signal_sum(
                bigwig,
                chromosome,
                int(start),
                int(end),
            )
        except RuntimeError:
            continue

    return wig_sum


def calculate_genome_wigsum(
    bigwig,
    chromosome_sizes: dict[str, int],
    chunk_size: int,
) -> float:
    """Calculate WIG sum across the entire BigWig."""
    wig_sum = 0.0

    for chromosome, chromosome_size in chromosome_sizes.items():
        if bigwig.stats(chromosome, 0, chromosome_size)[0] is None:
            print(f"Skip {chromosome}!", file=sys.stderr)
            continue

        print(f"Processing {chromosome} ...", file=sys.stderr)

        for _, start, end in chromosome_chunks(
            chromosome,
            chromosome_size,
            chunk_size,
        ):
            wig_sum += signal_sum(bigwig, chromosome, start, end)

    return wig_sum


def write_wig_chromosome(
    output,
    bigwig,
    chromosome: str,
    chromosome_size: int,
    chunk_size: int,
    weight: float,
) -> None:
    """Write one chromosome in variableStep WIG format."""
    print(f"Writing {chromosome} ...", file=sys.stderr)
    output.write(f"variableStep chrom={chromosome}\n")

    for _, start, end in chromosome_chunks(
        chromosome,
        chromosome_size,
        chunk_size,
    ):
        values = bigwig.values(chromosome, start, end)
        values = np.nan_to_num(values) * weight

        coordinate = start

        for value in values:
            coordinate += 1
            if value != 0:
                print(f"{coordinate}\t{value:.2f}", file=output)


def write_bedgraph_chromosome(
    output,
    bigwig,
    chromosome: str,
    chromosome_size: int,
    chunk_size: int,
    weight: float,
) -> None:
    """Write one chromosome in bedGraph format using the original grouping."""
    print(f"Writing {chromosome} ...", file=sys.stderr)

    for _, start, end in chromosome_chunks(
        chromosome,
        chromosome_size,
        chunk_size,
    ):
        value_to_positions: collections.defaultdict[float, list[int]] = (
            collections.defaultdict(list)
        )
        range_to_value: dict[int, tuple[int, float]] = {}

        values = bigwig.values(chromosome, start, end)
        values = np.nan_to_num(values) * weight

        coordinate = start

        for value in values:
            coordinate += 1
            if value != 0:
                value_to_positions[float(value)].append(coordinate)

        for value, positions in value_to_positions.items():
            groups = groupby(
                enumerate(positions),
                lambda indexed_position: (
                    indexed_position[0] - indexed_position[1]
                ),
            )

            for _, group in groups:
                contiguous_positions = list(map(itemgetter(1), group))
                range_to_value[contiguous_positions[0] - 1] = (
                    len(contiguous_positions),
                    value,
                )

        for range_start in sorted(range_to_value):
            length, value = range_to_value[range_start]
            print(
                f"{chromosome}\t{range_start}\t"
                f"{range_start + length}\t{value}",
                file=output,
            )


def normalize_bigwig(
    bigwig_file: Path,
    output_file: Path,
    *,
    total_wigsum: float,
    refgene_bed: Path | None,
    chunk_size: int,
    output_format: str,
) -> tuple[float, float]:
    """Normalize a BigWig and write WIG or bedGraph output."""
    bigwig = pyBigWig.open(str(bigwig_file))

    if bigwig is None:
        raise OSError(f"could not open BigWig file: {bigwig_file}")

    try:
        if not bigwig.isBigWig():
            raise ValueError(f"{bigwig_file} is not a BigWig file")

        print(
            "Get chromosome sizes from BigWig header ...",
            file=sys.stderr,
        )
        chromosome_sizes = {
            chromosome: int(size)
            for chromosome, size in bigwig.chroms().items()
        }

        if refgene_bed is not None:
            observed_wigsum = calculate_exonic_wigsum(
                bigwig,
                refgene_bed,
            )
        else:
            print(
                f"Calculate WIG sum from {bigwig_file}",
                file=sys.stderr,
            )
            observed_wigsum = calculate_genome_wigsum(
                bigwig,
                chromosome_sizes,
                chunk_size,
            )

        print(
            f"\nTotal WIG sum is {observed_wigsum:.2f}\n",
            file=sys.stderr,
        )

        if observed_wigsum <= 0:
            raise ValueError(
                "observed WIG sum is zero; normalization cannot be calculated"
            )

        weight = total_wigsum / observed_wigsum

        print(
            f"Normalization factor: {weight:.12g}",
            file=sys.stderr,
        )
        print("Normalizing BigWig file ...", file=sys.stderr)

        with output_file.open("w", encoding="utf-8") as output:
            for chromosome, chromosome_size in chromosome_sizes.items():
                if (
                    bigwig.stats(
                        chromosome,
                        0,
                        chromosome_size,
                    )[0]
                    is None
                ):
                    print(f"Skip {chromosome}!", file=sys.stderr)
                    continue

                if output_format == "wig":
                    write_wig_chromosome(
                        output,
                        bigwig,
                        chromosome,
                        chromosome_size,
                        chunk_size,
                        weight,
                    )
                else:
                    write_bedgraph_chromosome(
                        output,
                        bigwig,
                        chromosome,
                        chromosome_size,
                        chunk_size,
                        weight,
                    )

        return observed_wigsum, weight

    finally:
        bigwig.close()


def main(argv: Sequence[str] | None = None) -> int:
    """Run BigWig normalization."""
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_args(parser, args)

    try:
        observed_wigsum, weight = normalize_bigwig(
            bigwig_file=args.bigwig_file,
            output_file=args.output_file,
            total_wigsum=args.total_wigsum,
            refgene_bed=args.refgene_bed,
            chunk_size=args.chunk_size,
            output_format=args.out_format,
        )

        print(f"Created: {args.output_file}", file=sys.stderr)
        print(
            f"Observed WIG sum: {observed_wigsum:.2f}",
            file=sys.stderr,
        )
        print(
            f"Applied normalization factor: {weight:.12g}",
            file=sys.stderr,
        )

    except (OSError, ValueError, RuntimeError) as exc:
        parser.exit(1, f"{parser.prog}: error: {exc}\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())

