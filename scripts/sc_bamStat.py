"""Report mapping statistics for single-cell RNA-seq BAM files.

This command is intended for BAM files generated by Cell Ranger or compatible
pipelines that provide cellular-barcode, UMI, region, transcript-strand, and
feature-assignment tags.
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path
from typing import Sequence

from qcmodule import scbam


__author__ = "Liguo Wang"
__version__ = "5.05"

DESCRIPTION = (
    "Report single-cell RNA-seq mapping statistics from a tagged BAM file, "
    "such as a BAM produced by Cell Ranger."
)

EPILOG = """
Default BAM tags
----------------
CB
    Error-corrected cellular barcode.

UB
    Error-corrected unique molecular identifier (UMI).

RE
    Alignment region type: E = exonic, N = intronic, I = intergenic.

TX
    Alignment is on the same strand as an annotated transcript.

AN
    Alignment is on the antisense strand of an annotated transcript.

xf
    Alignment is confidently assigned to a feature.

Example
-------
sc_bamStat.py \
    -i possorted_genome_bam.bam \
    --chrM-id chrM
"""


def build_parser() -> argparse.ArgumentParser:
    """Create and configure the command-line parser."""
    parser = argparse.ArgumentParser(
        description=DESCRIPTION,
        epilog=EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "-i",
        "--infile",
        dest="bam_file",
        required=True,
        type=Path,
        help="Input BAM file.",
    )
    parser.add_argument(
        "--cb-tag",
        dest="cb_tag",
        default="CB",
        metavar="TAG",
        help=(
            "BAM tag containing the error-corrected cellular barcode. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--re-tag",
        dest="re_tag",
        default="RE",
        metavar="TAG",
        help=(
            "BAM tag containing the alignment region type. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--tx-tag",
        dest="tx_tag",
        default="TX",
        metavar="TAG",
        help=(
            "BAM tag marking alignments on the transcript sense strand. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--an-tag",
        dest="an_tag",
        default="AN",
        metavar="TAG",
        help=(
            "BAM tag marking alignments on the transcript antisense strand. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--umi-tag",
        dest="umi_tag",
        default="UB",
        metavar="TAG",
        help=(
            "BAM tag containing the error-corrected UMI. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--xf-tag",
        dest="xf_tag",
        default="xf",
        metavar="TAG",
        help=(
            "BAM tag marking reads confidently assigned to a feature. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--chrM-id",
        dest="mit_contig_name",
        default="chrM",
        metavar="NAME",
        help=(
            "Mitochondrial contig name in the BAM header. "
            "Default: %(default)s"
        ),
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable detailed progress logging.",
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
    )

    return parser


def configure_logging(verbose: bool) -> None:
    """Configure command-line logging."""
    logging.basicConfig(
        format="%(asctime)s [%(levelname)s] %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
        level=logging.DEBUG if verbose else logging.INFO,
    )


def find_bam_index(bam_file: Path) -> Path | None:
    """Return an existing BAM index path using either standard convention."""
    candidates = (
        Path(f"{bam_file}.bai"),
        bam_file.with_suffix(".bai"),
    )

    for candidate in candidates:
        if candidate.is_file():
            return candidate

    return None


def validate_tag(
    parser: argparse.ArgumentParser,
    option_name: str,
    tag: str,
) -> None:
    """Validate a SAM/BAM auxiliary tag name."""
    if len(tag) != 2:
        parser.error(f"{option_name} must be exactly two characters")

    if any(character.isspace() for character in tag):
        parser.error(f"{option_name} cannot contain whitespace")


def validate_args(
    parser: argparse.ArgumentParser,
    args: argparse.Namespace,
) -> Path:
    """Validate command-line arguments and return the BAM index path."""
    if not args.bam_file.is_file():
        parser.error(f"input BAM file does not exist: {args.bam_file}")

    if args.bam_file.suffix.lower() != ".bam":
        parser.error(f"input file must have a .bam extension: {args.bam_file}")

    bam_index = find_bam_index(args.bam_file)
    if bam_index is None:
        parser.error(
            "cannot find BAM index; expected either "
            f"{args.bam_file}.bai or {args.bam_file.with_suffix('.bai')}"
        )

    for option_name, tag in (
        ("--cb-tag", args.cb_tag),
        ("--re-tag", args.re_tag),
        ("--tx-tag", args.tx_tag),
        ("--an-tag", args.an_tag),
        ("--umi-tag", args.umi_tag),
        ("--xf-tag", args.xf_tag),
    ):
        validate_tag(parser, option_name, tag)

    if not args.mit_contig_name.strip():
        parser.error("--chrM-id cannot be empty")

    return bam_index


def main(argv: Sequence[str] | None = None) -> int:
    """Run single-cell BAM mapping-statistics analysis."""
    parser = build_parser()
    args = parser.parse_args(argv)

    configure_logging(args.verbose)
    bam_index = validate_args(parser, args)

    logging.debug("Input BAM: %s", args.bam_file)
    logging.debug("BAM index: %s", bam_index)
    logging.debug(
        "Tags: CB=%s UMI=%s xf=%s RE=%s TX=%s AN=%s",
        args.cb_tag,
        args.umi_tag,
        args.xf_tag,
        args.re_tag,
        args.tx_tag,
        args.an_tag,
    )
    logging.debug("Mitochondrial contig: %s", args.mit_contig_name)

    try:
        scbam.mapping_stat(
            infile=str(args.bam_file),
            CB_tag=args.cb_tag,
            UMI_tag=args.umi_tag,
            xf_tag=args.xf_tag,
            RE_tag=args.re_tag,
            TX_tag=args.tx_tag,
            AN_tag=args.an_tag,
            chrM_id=args.mit_contig_name,
        )
    except (OSError, ValueError, RuntimeError, KeyError) as exc:
        logging.error("%s", exc)
        return 1

    logging.info("Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
